"""Layer 3 (AI_THREE_LAYER_REBUILD_PLAN.md §5.2): the adviser agent.

Two-phase, matching the pattern this codebase already uses for Layer 1/2
agents (assemble-then-interpret, gather-then-structure):

1. **Gather** (``gather_advice``): ``run_agent`` drives a multi-step tool
   loop with access to portfolio state (``PortfolioSnapshotTool``),
   Layer-1 interpretations (``InterpretationLookupTool``), Layer-2 news/
   research (``RecentNewsTool``/``ResearchReportLookupTool``), general
   analytics (``DataQueryTool``), web search, and the portfolio-action
   tools (``WhatIfTool``/``DriftAnalysisTool``/``PreTradeComplianceTool``)
   -- at SYNTHESIS tier (``router.FEATURE_TIER["adviser_chat"]``), since
   this is the conversational reasoning step, not every turn produces a
   formal recommendation.
2. **Extract** (``extract_recommendations``): a SEPARATE
   ``complete_structured`` call over the gather transcript, at DEEP tier
   (``router.FEATURE_TIER["adviser_recommendation"]``) -- pulls out zero
   or more concrete, actionable recommendations from what was actually
   discussed. Zero is a valid, common outcome: "what's my current NAV?"
   needs no recommendation.

Critically, ``whatif_impact``/``compliance`` on each extracted
recommendation are NOT trusted from the LLM's own prose -- ``
verify_recommendation`` (called by ``run_adviser_turn`` for any
recommendation with a concrete trade ``action``) re-runs the real
``portfolio_advisory.compute_whatif``/``check_pretrade_compliance``
against live data, the same "never trust the model for a number it could
look up" principle every other layer in this codebase already follows.
"""
from __future__ import annotations

import dataclasses
import uuid
from collections.abc import Awaitable, Callable
from dataclasses import dataclass

from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from src.ai.agents.loop import AgentResult, AgentStep, run_agent
from src.ai.models import Tier
from src.ai.tools.data_query import DataQueryTool
from src.ai.tools.entity_context import (
    InterpretationLookupTool,
    RecentNewsTool,
    ResearchReportLookupTool,
)
from src.ai.tools.portfolio import (
    DriftAnalysisTool,
    PortfolioSnapshotTool,
    PreTradeComplianceTool,
    WhatIfTool,
)
from src.ai.tools.web_search import web_search_tool_spec
from src.services import portfolio_advisory

# router.FEATURE_TIER["adviser_chat"] / ["adviser_recommendation"] -- see
# module docstring for why gather and extract run at different tiers.
GATHER_TIER = Tier.SYNTHESIS
EXTRACT_TIER = Tier.DEEP

MAX_ADVISER_ITERATIONS = 10

DISCLAIMER = (
    "This is not financial advice. All recommendations are generated by an AI system "
    "based on available data and should be independently verified before acting on them."
)

ADVISER_SYSTEM_PROMPT = f"""\
You are a financial adviser agent for a professional investor's portfolio, per \
AI_THREE_LAYER_REBUILD_PLAN.md Layer 3 (Financial Adviser) §5.2. You are given a \
portfolio to advise on and a goal or question.

Approach: gather context (portfolio holdings, Layer 1 interpretations, Layer 2 news/ \
research, relevant analytics) -> reason about what matters -> if you're proposing a \
concrete trade or rebalance, ALWAYS run whatif_trade_impact and \
pretrade_compliance_check on it first, and only recommend trades that pass compliance \
(or clearly flag ones that don't) -> respond with your reasoning and, when warranted, \
concrete proposed actions.

Ground every claim in what your tools actually return -- never invent a position, a \
number, a news event, or an interpretation you did not look up. When you don't have \
enough information to recommend something concrete, say so rather than guessing.

{DISCLAIMER}
"""


class RecommendationOutput(BaseModel):
    """Structured output for one extracted recommendation."""

    kind: str = Field(description="REBALANCE, RISK, OPPORTUNITY, THESIS, or HEDGE")
    action: dict = Field(
        default_factory=dict,
        description="Concrete action when applicable, e.g. {ticker, action, shares, price_per_share}. Empty dict for non-trade advice.",
    )
    rationale: str
    evidence: list[str] = Field(default_factory=list, description="What this is grounded in -- tool outputs, news, interpretations")
    confidence: float = Field(ge=0.0, le=1.0)


class AdviceExtractionOutput(BaseModel):
    recommendations: list[RecommendationOutput] = Field(default_factory=list)


EXTRACT_SYSTEM_PROMPT = """\
You are extracting concrete, actionable recommendations from a completed adviser \
conversation, per AI_THREE_LAYER_REBUILD_PLAN.md Layer 3 §5.2/§5.4. You are given the \
full transcript (tool calls, tool results, the adviser's own reasoning) -- NOT asked \
to do any further research or reasoning.

Extract zero or more recommendations. Zero is correct and common when the \
conversation was purely informational (a question answered, no action proposed). For \
each real recommendation actually present in the transcript:
- kind: REBALANCE (portfolio rebalancing), RISK (risk reduction), OPPORTUNITY (new \
  position), THESIS (a view without an immediate trade), or HEDGE.
- action: the concrete trade if one was proposed (ticker/action/shares/price_per_share), \
  else an empty object for advice with no specific trade.
- rationale: why, grounded in what the transcript actually found.
- evidence: what specifically supports this -- tool outputs, cited news, interpretations.
- confidence: lower when the transcript's own supporting evidence was thin.

Never invent a recommendation the transcript doesn't actually support.
"""


def render_transcript(steps: list[AgentStep]) -> str:
    """Pure: same rendering convention as
    ``src.ai.research.researcher.render_transcript``."""
    lines: list[str] = []
    for i, step in enumerate(steps, start=1):
        if step.text:
            lines.append(f"[Step {i} — adviser reasoning]\n{step.text}")
        for call, result in zip(step.tool_calls, step.tool_results):
            status = "ERROR" if result.get("is_error") else "OK"
            lines.append(
                f"[Step {i} — tool call: {call['name']}({call['input']}) -> {status}]\n{result['content']}"
            )
    return "\n\n".join(lines) if lines else "(no steps were recorded)"


async def gather_advice(
    client,
    session: AsyncSession,
    *,
    portfolio_id: uuid.UUID,
    message: str,
    on_step: Callable[[AgentStep], Awaitable[None]] | None = None,
) -> AgentResult:
    """Phase 1: drive the multi-step adviser reasoning loop for one turn.
    Raises if the client is disabled, matching every other agent in this
    codebase's convention."""
    if not client.enabled:
        raise RuntimeError("AI disabled: set ANTHROPIC_API_KEY and install 'anthropic'.")

    user = f"Portfolio ID: {portfolio_id}\n\n{message}"
    return await run_agent(
        client=client,
        system=ADVISER_SYSTEM_PROMPT,
        user=user,
        tools=[
            PortfolioSnapshotTool(session), WhatIfTool(session), DriftAnalysisTool(session),
            PreTradeComplianceTool(session), DataQueryTool(session),
            InterpretationLookupTool(session), RecentNewsTool(session), ResearchReportLookupTool(session),
        ],
        server_tools=[web_search_tool_spec()],
        tier=GATHER_TIER,
        max_tokens=4096,
        max_iterations=MAX_ADVISER_ITERATIONS,
        feature="adviser_chat",
        on_step=on_step,
    )


async def extract_recommendations(
    client, agent_result: AgentResult,
) -> list[RecommendationOutput]:
    """Phase 2: pull structured recommendations (possibly none) out of a
    completed gather pass's transcript."""
    transcript = render_transcript(agent_result.steps)
    output = await client.complete_structured(
        response_model=AdviceExtractionOutput,
        user=f"<adviser_transcript>\n{transcript}\n</adviser_transcript>",
        system=EXTRACT_SYSTEM_PROMPT,
        tier=EXTRACT_TIER,
        max_tokens=2048,
        feature="adviser_recommendation",
    )
    return output.recommendations


@dataclass(frozen=True)
class VerifiedRecommendation:
    recommendation: RecommendationOutput
    whatif_impact: dict | None
    compliance: dict | None


def _trade_action_fields(action: dict) -> tuple[str, str, float, float] | None:
    """Extract (ticker, action, shares, price_per_share) from a
    recommendation's free-form ``action`` dict, or ``None`` if it isn't a
    well-formed single trade (e.g. non-trade advice, or a multi-leg
    rebalance the adviser described in prose rather than one concrete
    order -- verification is deliberately scoped to the single-trade case
    this pass handles, not a general multi-leg simulator)."""
    ticker = action.get("ticker")
    trade_action = action.get("action")
    shares = action.get("shares")
    price = action.get("price_per_share")
    if not ticker or not trade_action or shares is None or price is None:
        return None
    try:
        return str(ticker), str(trade_action), float(shares), float(price)
    except (TypeError, ValueError):
        return None


async def verify_recommendation(
    session: AsyncSession, portfolio_id: uuid.UUID, rec: RecommendationOutput,
) -> VerifiedRecommendation:
    """Re-run real whatif + compliance checks against live data for a
    recommendation with a concrete single-trade ``action`` -- never trust
    the LLM's own account of what whatif/compliance said. Non-trade
    recommendations (or multi-leg ones this pass doesn't parse) pass
    through with ``whatif_impact``/``compliance`` left ``None``, not
    fabricated.
    """
    fields = _trade_action_fields(rec.action)
    if fields is None:
        return VerifiedRecommendation(recommendation=rec, whatif_impact=None, compliance=None)
    ticker, trade_action, shares, price = fields

    whatif_result = await portfolio_advisory.compute_whatif(
        session, portfolio_id, [{"ticker": ticker, "action": trade_action, "shares": shares, "price_per_share": price}],
    )
    compliance_result = await portfolio_advisory.check_pretrade_compliance(
        session, portfolio_id, ticker=ticker, action=trade_action, shares=shares, price=price,
    )
    return VerifiedRecommendation(
        recommendation=rec,
        whatif_impact=dataclasses.asdict(whatif_result) if whatif_result is not None else None,
        compliance=(
            {"approved": compliance_result.approved, "violations": compliance_result.violations, "warnings": compliance_result.warnings}
            if compliance_result is not None else None
        ),
    )


@dataclass(frozen=True)
class AdviserTurnResult:
    reply_text: str
    recommendations: list[VerifiedRecommendation]


async def run_adviser_turn(
    client,
    session: AsyncSession,
    *,
    portfolio_id: uuid.UUID,
    message: str,
    on_step: Callable[[AgentStep], Awaitable[None]] | None = None,
) -> AdviserTurnResult:
    """Full pipeline for one adviser turn: gather, extract recommendations
    (if any), verify each against live whatif/compliance data. Raises if
    the client is disabled (same convention as ``gather_advice``)."""
    agent_result = await gather_advice(client, session, portfolio_id=portfolio_id, message=message, on_step=on_step)
    raw_recommendations = await extract_recommendations(client, agent_result)
    verified = [await verify_recommendation(session, portfolio_id, r) for r in raw_recommendations]
    return AdviserTurnResult(reply_text=agent_result.final_text, recommendations=verified)
